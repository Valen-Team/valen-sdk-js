test('bbox_blocks keeps each bbox question in its own block',()=>{
 // state, state | glue | Q1 | Q2 | Q3 | glue | readouts 1, 2, 3; rows as valen_sdk.onnx.block_attention_mask gives them.
 const segments=[-1,-1,0,1,2,3,0,1,2,3],rows=(mode,bbox)=>visible(blockAttentionMask(mode,segments,2,bbox),10);
 const state='1100000000',glue='1110001000',merged='1111111111';
 // Question 2 is bbox: the decision questions 1 and 3 share block 1.
 assert.deepEqual(rows('bbox_blocks',[2]),[state,state,glue,'1111011101','1110101010','1111011101',glue,'1111011101','1110101010','1111011101']);
 assert.deepEqual(rows('bbox_blocks'),[state,state,glue,merged,merged,merged,glue,merged,merged,merged]);
 const one='1111001100',two='1110101010',three='1110011001';
 assert.deepEqual(rows('bbox_blocks',[2,3]),[state,state,glue,one,two,three,glue,one,two,three]);
 assert.deepEqual(rows('question_blocks'),[state,state,glue,one,two,three,glue,one,two,three]);
 // The reference keeps bbox block 1 as 1 and also merges the decision blocks into 1, so they share a block.
 assert.deepEqual(rows('bbox_blocks',[1]),[state,state,glue,merged,merged,merged,glue,merged,merged,merged]);
 const first='1111101110';
 assert.deepEqual(rows('bbox_blocks',[1,3]),[state,state,glue,first,first,three,glue,first,first,three]);
});
